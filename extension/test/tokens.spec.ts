// The frames' plain-CSS token sheet (static/tokens.css, design review R4),
// checked without a browser: it is what scripts/tokens-css.mjs writes from
// the installed @unicron/tokens, so a tokens update can't leave it behind.
import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

test("static/tokens.css is current with @unicron/tokens", () => {
  // Exits non-zero, and so throws, when the sheet differs from the generator's output.
  const out = execFileSync(process.execPath, ["scripts/tokens-css.mjs", "--check"], { cwd: root, encoding: "utf8" });
  expect(out).toContain("matches @unicron/tokens");
});

test("the frame links unicron's roles before its own sheet, and the build ships both", async () => {
  const html = await readFile(new URL("../static/frame.html", import.meta.url), "utf8");
  expect(html.indexOf('href="tokens.css"')).toBeGreaterThan(0);
  expect(html.indexOf('href="tokens.css"')).toBeLessThan(html.indexOf('href="ui.css"'));
  const sheet = await readFile(new URL("../dist/chromium/tokens.css", import.meta.url), "utf8");
  expect(sheet).toMatch(/Generated by scripts\/tokens-css\.mjs from @unicron\/tokens \d+\.\d+\.\d+/);
  // Dark follows the browser's scheme, as a frame can't be given a class.
  expect(sheet).toContain("@media (prefers-color-scheme: dark)");
  expect(sheet).not.toContain(".dark");
});
